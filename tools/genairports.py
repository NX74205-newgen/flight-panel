"""Generates src/airports_db.h from the OurAirports database (public domain): IATA -> city.

Usage:  python tools/genairports.py [path/to/airports.csv]
Without an argument it downloads https://davidmegginson.github.io/ourairports-data/airports.csv
"""
import csv
import io
import re
import sys
import unicodedata
import urllib.request
from pathlib import Path

URL = "https://davidmegginson.github.io/ourairports-data/airports.csv"
MAX_LEN = 22  # longer is pointless on the panel: it is shown in the marquee


def ascii_fold(s: str) -> str:
    s = unicodedata.normalize("NFKD", s)
    s = "".join(c for c in s if ord(c) < 128 and not unicodedata.combining(c))
    return re.sub(r"\s+", " ", s).strip()


def city_of(row) -> str:
    city = re.sub(r"\s*\(.*?\)\s*", " ", row["municipality"] or "")
    city = re.sub(r"\s*/.*$", "", city)  # "A / B" -> "A"
    city = ascii_fold(city)
    if len(city) < 2:  # no city: use the airport name without "International Airport"
        name = re.sub(r"\b(International|Intl\.?|Regional|Airport|Airfield|Air Base|Aerodrome)\b", "", row["name"])
        city = ascii_fold(name)
    city = city.replace("\\", "").replace('"', "'").strip(" -,")
    return city[:MAX_LEN].rstrip()


def main():
    if len(sys.argv) > 1:
        text = Path(sys.argv[1]).read_text(encoding="utf-8")
    else:
        with urllib.request.urlopen(URL, timeout=60) as r:
            text = r.read().decode("utf-8")

    rank = {"large_airport": 0, "medium_airport": 1, "small_airport": 2, "seaplane_base": 3, "heliport": 4}
    best = {}
    for row in csv.DictReader(io.StringIO(text)):
        code = (row["iata_code"] or "").strip().upper()
        if not re.fullmatch(r"[A-Z0-9]{3}", code) or row["type"] == "closed":
            continue
        city = city_of(row)
        if not city:
            continue
        r = rank.get(row["type"], 5)
        if code not in best or r < best[code][0]:  # duplicate code: prefer the larger airport
            best[code] = (r, city)

    codes = sorted(best)
    out = ["// Generated by tools/genairports.py from OurAirports (public domain) — do not edit.",
           "#pragma once", "",
           f"static constexpr int AIRPORT_DB_SIZE = {len(codes)};",
           "// 3 characters per code, sorted — binary search",
           "static const char AIRPORT_DB_CODES[] ="]
    for i in range(0, len(codes), 24):
        out.append('  "' + "".join(codes[i:i + 24]) + '"')
    out[-1] += ";"
    out.append("static const char *const AIRPORT_DB_CITY[] = {")
    for i in range(0, len(codes), 6):
        out.append("  " + " ".join(f'"{best[c][1]}",' for c in codes[i:i + 6]))
    out.append("};")

    dst = Path(__file__).resolve().parent.parent / "src" / "airports_db.h"
    dst.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"{dst}: {len(codes)} airports")


if __name__ == "__main__":
    main()
