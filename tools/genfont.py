FIRST, LAST = 0x20, 0x7E
H = 7


def pack(rows):
    bits = "".join(r.replace('.', '0').replace('#', '1') for r in rows)
    bits += "0" * (-len(bits) % 8)
    return [int(bits[i:i + 8], 2) for i in range(0, len(bits), 8)]


bitmap, glyphs, cache = [], [], {}
for code in range(FIRST, LAST + 1):
    ch = chr(code)
    key = ch.upper() if ch.upper() in G else (ch if ch in G else '?')
    rows = G[key]
    w = len(rows[0])
    assert all(len(r) == w for r in rows) and len(rows) == H, key
    if key not in cache:
        cache[key] = len(bitmap)
        bitmap += pack(rows)
    adv = w + 1 if key != ' ' else 2
    w_out = 0 if key == ' ' else w
    glyphs.append((cache[key], w_out, H if w_out else 0, adv, 0, -(H - 1), ch))

out = ["// Generated by tools/genfont.py — do not edit by hand.",
       "#pragma once", "#include <Adafruit_GFX.h>", "",
       "static const uint8_t PanelFontBitmaps[] PROGMEM = {"]
for i in range(0, len(bitmap), 12):
    out.append("  " + ", ".join(f"0x{b:02X}" for b in bitmap[i:i + 12]) + ",")
out.append("};\n\nstatic const GFXglyph PanelFontGlyphs[] PROGMEM = {")
for off, w, h, adv, xo, yo, ch in glyphs:
    c = ch if ch not in "\\'" else "\\" + ch
    out.append(f"  {{{off:4d}, {w}, {h}, {adv}, {xo}, {yo}}},  // '{c}'")
out.append("};\n")
out.append(f"static const GFXfont PanelFont PROGMEM = {{(uint8_t *)PanelFontBitmaps, "
           f"(GFXglyph *)PanelFontGlyphs, 0x{FIRST:02X}, 0x{LAST:02X}, 8}};")

dst = Path(__file__).resolve().parent.parent / "src" / "font_panel.h"
dst.write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"{dst}: {len(bitmap)} bytes bitmap, {len(glyphs)} glyphs")
